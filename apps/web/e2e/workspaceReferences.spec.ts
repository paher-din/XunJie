import { test, expect, type Page } from '@playwright/test'
import { REAL_URL } from './env'

const material = (page: Page) => page.getByLabel('组合逻辑学习材料', { exact: true })
const refs = (page: Page) => page.getByRole('region', { name: '上下文引用' }).locator('li')
const question = (page: Page) => page.getByRole('textbox', { name: '你的问题', exact: true })
const ask = (page: Page) => page.getByRole('button', { name: '询问 Agent', exact: true })

async function start(page: Page) {
  await page.goto(`${REAL_URL}/#/dev/workspace-references`)
  await expect(page.getByRole('heading', { name: '选区引用组件验收' })).toBeVisible()
  await expect(page.locator('.monaco-editor textarea.inputarea')).toBeAttached()
}
/** Read layout only; the browser's pointer selection, not an internal state setter, performs the operation. */
async function selectText(page: Page, text: string) {
  const source = material(page)
  await source.scrollIntoViewIfNeeded()
  const points = await source.evaluate((el, text) => {
    const node = el.firstChild!, start = node.textContent!.indexOf(text), end = start + text.length
    if (start < 0) throw new Error('Text not present')
    const first = document.createRange(), last = document.createRange()
    first.setStart(node, start); first.setEnd(node, start + 1)
    last.setStart(node, end - 1); last.setEnd(node, end)
    const a = first.getBoundingClientRect(), b = last.getBoundingClientRect()
    return { x1: a.left + .2, y1: a.top + a.height / 2, x2: b.right - .2, y2: b.top + b.height / 2 }
  }, text)
  await page.mouse.click(points.x1, points.y1) // Collapse any prior native selection before a fresh drag.
  await page.mouse.move(points.x1, points.y1)
  await page.mouse.down()
  await page.mouse.move(points.x2, points.y2, { steps: 12 })
  await page.mouse.up()
}
async function selectCode(page: Page) {
  const editor = page.locator('.monaco-editor textarea.inputarea')
  await editor.focus()
  const modifier = await page.evaluate(() => navigator.userAgent.includes('Macintosh') ? 'Meta' : 'Control')
  await page.keyboard.press(`${modifier}+a`)
}
async function selectCodeFirstLine(page: Page) {
  const line = page.locator('.monaco-editor .view-line').filter({ hasText: /样例代码：中文/ })
  await page.getByLabel('demo.sv', { exact: true }).scrollIntoViewIfNeeded()
  await expect(line).toContainText('// 样例代码：中文 🧩')
  const box = await line.evaluate(element => {
    const range = document.createRange(); range.selectNodeContents(element)
    const rect = range.getBoundingClientRect()
    return { left: rect.left, right: rect.right, y: rect.top + rect.height / 2 }
  })
  await page.mouse.move(box.left + .2, box.y); await page.mouse.down()
  await page.mouse.move(box.right - .2, box.y, { steps: 12 }); await page.mouse.up()
}
async function receipt(page: Page) { return JSON.parse((await page.getByTestId('reference-receipt').textContent())!) }

