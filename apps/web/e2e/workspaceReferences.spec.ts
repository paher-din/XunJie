test('代码鼠标选区与普通文字可混合引用；移除后焦点通知不复活', async ({ page }) => {
  await start(page)
  await selectCode(page)
  await page.keyboard.press('ArrowRight')
  await page.keyboard.insertText('\n' + Array.from({ length: 60 }, (_, i) => `// scroll ${i}`).join('\n'))
  await expect(page.locator('.monaco-editor .view-lines')).toContainText('// scroll 59')
  await selectCode(page)
  await page.keyboard.press('ArrowLeft')
  await selectCodeFirstLine(page)
  await expect(ask(page)).toBeVisible()
  await ask(page).click()
  await expect(refs(page)).toHaveCount(1)
  expect(await refs(page).first().locator('pre').textContent()).toBe('// 样例代码：中文 🧩')
  await selectText(page, '请比较两种逻辑对时钟的依赖。')
  await expect(refs(page)).toHaveCount(2)
  await page.getByRole('button', { name: '移除引用 1', exact: true }).click()
  await page.locator('.monaco-editor textarea.inputarea').focus()
  // Pointer down/up on a non-selection surface must not re-add the retained Monaco range.
  const scrollbar = page.locator('.monaco-editor .scrollbar.vertical .slider').first()
  await scrollbar.click({ force: true })
  await page.evaluate(() => document.dispatchEvent(new Event('selectionchange')))
  await expect(refs(page)).toHaveCount(1)
  expect(await refs(page).first().locator('pre').textContent()).toBe('请比较两种逻辑对时钟的依赖。')
  await page.getByRole('button', { name: '定位引用 1：组合逻辑学习材料', exact: true }).click()
  await expect.poll(() => page.evaluate(() => document.getSelection()?.toString())).toBe('请比较两种逻辑对时钟的依赖。')
  await expect(refs(page)).toHaveCount(1)
  await selectCodeFirstLine(page)
  await expect(refs(page)).toHaveCount(2)
  expect(await refs(page).nth(1).locator('pre').textContent()).toBe('// 样例代码：中文 🧩')
})

test('缩放后工具条限制在可见视口，Escape 可撤销入口', async ({ page }) => {
  await start(page)
  await selectText(page, '先观察输入，再解释输出。')
  await expect(ask(page)).toBeVisible()
  const cdp = await page.context().newCDPSession(page)
  await cdp.send('Emulation.setPageScaleFactor', { pageScaleFactor: 1.5 })
  await expect.poll(async () => {
    const bounds = await ask(page).boundingBox()
    const viewport = await page.evaluate(() => ({ x: visualViewport!.offsetLeft, y: visualViewport!.offsetTop,
      width: visualViewport!.width, height: visualViewport!.height }))
    return !!bounds && bounds.x >= viewport.x && bounds.y >= viewport.y &&
      bounds.x + bounds.width <= viewport.x + viewport.width && bounds.y + bounds.height <= viewport.y + viewport.height
  }).toBe(true)
  await page.keyboard.press('Escape')
  await expect(ask(page)).toHaveCount(0)
  await cdp.detach()
})

for (const widget of ['find', 'replace'] as const) test(`编辑器 ${widget} 输入内全选不复活已移除代码引用`, async ({ page }) => {
  await start(page)
  await page.getByRole('button', { name: '打开对话' }).click()
  await selectCode(page)
  await expect(refs(page)).toHaveCount(1)
  await page.getByRole('button', { name: '移除引用 1', exact: true }).click()
  await expect(refs(page)).toHaveCount(0)
  await page.locator('.monaco-editor textarea.inputarea').focus()
  const modifier = await page.evaluate(() => navigator.userAgent.includes('Macintosh') ? 'Meta' : 'Control')
  await page.keyboard.press(widget === 'find' ? `${modifier}+f` : `${modifier}+h`)
  const input = page.locator(widget === 'find' ? '.find-widget .find-part textarea' : '.find-widget .replace-part textarea')
  await expect(input).toBeVisible()
  await input.fill('widget-only-query')
  await input.focus()
  await page.keyboard.press(`${modifier}+a`)
  // Flush the same animation frame used to complete a keyboard gesture before observing absence.
  await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))))
  await expect(refs(page)).toHaveCount(0)
  await page.keyboard.press('Shift+ArrowLeft')
  await page.evaluate(() => new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))))
  await expect(refs(page)).toHaveCount(0)
  await page.keyboard.press('Escape')
  await selectCode(page)
  await expect(refs(page)).toHaveCount(1)
  expect(await refs(page).first().locator('pre').textContent()).toContain('module demo;')
  await page.getByRole('button', { name: '移除引用 1', exact: true }).click()
  await page.locator('.monaco-editor textarea.inputarea').focus()
  await page.keyboard.press('ArrowLeft')
  await page.keyboard.press('Shift+ArrowRight')
  await expect(refs(page)).toHaveCount(1)
  expect(await refs(page).first().locator('pre').textContent()).toBe('/')
})

