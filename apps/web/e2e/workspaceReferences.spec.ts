  await expect(refs(page)).toHaveCount(1)
  expect(await refs(page).first().locator('pre').textContent()).toBe(text)
  await expect(question(page)).toBeFocused()
  await question(page).fill('为什么需要时钟？')
  await page.getByRole('button', { name: '收起对话' }).click()
  await page.getByRole('button', { name: '打开对话' }).click()
  await expect(question(page)).toHaveValue('为什么需要时钟？')
  await expect(refs(page)).toHaveCount(1)
  await selectText(page, text)
  await expect(refs(page)).toHaveCount(1)
  await page.getByRole('button', { name: '移除引用 1', exact: true }).click()
  await page.evaluate(() => { document.dispatchEvent(new Event('selectionchange')); document.dispatchEvent(new Event('selectionchange')) })
  await question(page).focus()
  await expect(refs(page)).toHaveCount(0)
  await selectText(page, text)
  await expect(refs(page)).toHaveCount(1)
  await selectText(page, '请比较两种逻辑对时钟的依赖。')
  await expect(refs(page)).toHaveCount(2)
  await expect(page.getByTestId('reference-receipt')).toHaveCount(0)
