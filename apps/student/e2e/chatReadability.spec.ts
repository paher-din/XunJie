import { test, expect } from '@playwright/test'
import { start } from './helpers'

test('工作区大幅阅读、多行与IME、问答顺序、收起保留草稿和窄屏', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await start(page, 'chat-reading')
  await page.getByRole('button', { name: '就项目求助', exact: true }).click()
  const pane = page.getByTestId('tutoring-pane')
  const box = await pane.boundingBox()
  expect(box!.width).toBeGreaterThanOrEqual(560)
  expect(box!.height).toBeGreaterThanOrEqual(600)
  const input = page.getByRole('textbox', { name: '就这个任务提问' })
  await expect(input).toHaveJSProperty('tagName', 'TEXTAREA')
  const requests: string[] = []
  page.on('request', r => { if (r.method() === 'POST' && r.url().endsWith('/help')) requests.push(r.postData()!) })
  await input.fill('第一个问题')
  await input.press('Shift+Enter')
  await input.pressSequentially('多行补充')
  await expect(input).toHaveValue('第一个问题\n多行补充')
  await input.dispatchEvent('keydown', { key: 'Enter', isComposing: true })
  expect(requests).toHaveLength(0)
  await input.press('Enter')
  await expect(page.getByTestId('tutor-message')).toHaveCount(1)
  await expect(input).toHaveValue('')
  await input.fill('第二个问题')
  await input.press('Enter')
  await expect(page.getByTestId('tutor-message')).toHaveCount(2)
  expect(await pane.locator('[data-testid=tutor-question-status], [data-testid=tutor-message]').evaluateAll(nodes => nodes.map(n => n.getAttribute('data-testid'))))
    .toEqual(['tutor-question-status', 'tutor-message', 'tutor-question-status', 'tutor-message'])
  await input.fill('继续输入但暂不发送')
  await page.getByRole('button', { name: '展开阅读', exact: true }).click()
  expect((await pane.boundingBox())!.width).toBeGreaterThan(box!.width)
  await page.getByRole('button', { name: '收起辅导', exact: true }).click()
  await page.getByRole('button', { name: '就项目求助', exact: true }).click()
  await expect(input).toHaveValue('继续输入但暂不发送')
  await page.setViewportSize({ width: 390, height: 844 })
  const narrow = await pane.boundingBox()
  expect(narrow!.x).toBeGreaterThanOrEqual(0)
  expect(narrow!.x + narrow!.width).toBeLessThanOrEqual(390)
  expect(narrow!.y).toBeGreaterThanOrEqual(0)
  expect(narrow!.y + narrow!.height).toBeLessThanOrEqual(844)
  await expect(input).toBeInViewport()
})
